export function articleDate(date: string) {
  return new Intl.DateTimeFormat("ru-RU", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  }).format(new Date(date + "T00:00:00Z"));
}
export function articleReadTime(article: Article) {
  const text = article.blocks
    .map((b) =>
      b.type === "table"
        ? [b.caption, ...b.headings, ...b.rows.flat()].join(" ")
        : b.type === "list"
          ? b.items.join(" ")
          : b.text,
    )
    .join(" ");
  return Math.max(1, Math.ceil(text.trim().split(/\s+/).length / 180));
}
